"""The RSS/Atom feed list for KOReader's News Downloader plugin (#5).

The list lives in feeds.toml (shipped with the package, or a file of your own) and is rendered into
the plugin's Lua config at koreader/news/feed_config.lua on each Kindle. On a Kindle, KOReader's
data directory is its install directory (datastorage.lua: data_dir = "."), and the plugin reads
<data dir>/news/feed_config.lua (newsdownloader.koplugin/main.lua, KOReader v2026.07.1).
"""

import argparse
import logging
import re
import sys
import tomllib
import urllib.error
import urllib.request
import xml.etree.ElementTree as ET

from dataclasses import dataclass
from importlib.resources import files
from pathlib import Path

from koreader_d00901 import __version__
from koreader_d00901.errors import ConfigError

log = logging.getLogger(__name__)

SECTIONS = ('security', 'engineering', 'research')
FEED_CONFIG = ('koreader', 'news', 'feed_config.lua')
MAX_AGE = re.compile(r'^[1-9][0-9]*[smhdwMy]$')
USER_AGENT = f'koreader-d00901/{__version__} feed-check'


@dataclass(frozen=True)
class Feed:
    name: str
    section: str
    url: str
    limit: int
    max_age: str | None = None
    full_article: bool = False
    enabled: bool = True
    check: bool = True
    note: str = ''


def _feed(entry: dict, index: int) -> Feed:
    where = f'feed #{index} ({entry.get("name", "unnamed")})'
    allowed = set(Feed.__dataclass_fields__)
    if unknown := set(entry) - allowed:
        raise ConfigError(f'{where}: unknown field(s) {", ".join(sorted(unknown))}')
    try:
        feed = Feed(**entry)
    except TypeError as exc:
        raise ConfigError(f'{where}: {exc}') from None
    if not feed.url.startswith(('https://', 'http://')):
        raise ConfigError(f'{where}: url must be http(s): {feed.url!r}')
    if feed.section not in SECTIONS:
        raise ConfigError(f'{where}: section must be one of {", ".join(SECTIONS)}')
    if not isinstance(feed.limit, int) or isinstance(feed.limit, bool) or feed.limit < 0:
        raise ConfigError(f'{where}: limit must be a whole number >= 0')
    if feed.max_age is not None and not MAX_AGE.match(feed.max_age):
        raise ConfigError(f'{where}: max_age must look like "7d" or "12h", not {feed.max_age!r}')
    return feed


def load_feeds(path: Path | None = None) -> list[Feed]:
    """Feeds from a TOML file, or the list shipped with the package."""
    source = path.read_text() if path is not None else files('koreader_d00901').joinpath('feeds.toml').read_text()
    try:
        data = tomllib.loads(source)
    except tomllib.TOMLDecodeError as exc:
        raise ConfigError(f'{path or "feeds.toml"}: {exc}') from exc
    feeds = [_feed(entry, i) for i, entry in enumerate(data.get('feed', []), 1)]
    if not any(feed.enabled for feed in feeds):
        raise ConfigError(f'{path or "feeds.toml"}: no enabled feeds')
    return feeds


def _lua(value: str) -> str:
    return '"' + value.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n') + '"'


def render_lua(feeds: list[Feed]) -> str:
    """The News Downloader feed_config.lua for these feeds, disabled ones commented out."""
    lines = [
        'return {--do NOT change this line',
        '-- Generated by koreader-d00901 from feeds.toml. Edit the TOML in the repo and rerun',
        '-- `koreader-d00901 --only feeds` instead of editing this file on the Kindle.',
    ]
    for section in SECTIONS:
        group = [feed for feed in feeds if feed.section == section]
        if not group:
            continue
        lines += ['', f'-- {section.upper()}']
        for feed in group:
            fields = [_lua(feed.url), f'limit = {feed.limit}']
            if feed.max_age:
                fields.append(f'max_age = {_lua(feed.max_age)}')
            fields += [f'download_full_article = {str(feed.full_article).lower()}', 'include_images = false']
            lines.append(f'-- {feed.name}' + (f' ({feed.note})' if feed.note else ''))
            lines.append(('' if feed.enabled else '-- ') + '{ ' + ', '.join(fields) + ' },')
    lines += ['', '}--do NOT change this line', '']
    return '\n'.join(lines)


def install_feeds(mount: Path, feeds: list[Feed]) -> Path:
    """Write feed_config.lua onto the Kindle, keeping a .bak of a different existing file."""
    target = mount.joinpath(*FEED_CONFIG)
    target.parent.mkdir(parents=True, exist_ok=True)
    text = render_lua(feeds)
    if target.exists() and target.read_text() != text:
        backup = target.with_name(target.name + '.bak')
        target.replace(backup)
        log.info('kept the previous feed list as %s', backup)
    target.write_text(text)
    log.info('wrote %d feeds (%d enabled) to %s', len(feeds), sum(f.enabled for f in feeds), target)
    return target


def check_feed(feed: Feed, timeout: int = 30) -> str | None:
    """None when the feed downloads and parses as RSS/Atom with items, else the problem."""
    request = urllib.request.Request(feed.url, headers={'User-Agent': USER_AGENT})
    try:
        with urllib.request.urlopen(request, timeout=timeout) as response:
            body = response.read()
        root = ET.fromstring(body)
    except (urllib.error.URLError, TimeoutError, ET.ParseError) as exc:
        return f'{feed.name}: {exc}'
    items = [el for el in root.iter() if el.tag.rsplit('}', 1)[-1] in ('item', 'entry')]
    if not items:
        return f'{feed.name}: parsed, but has no items'
    log.debug('%s: %d items, %d bytes', feed.name, len(items), len(body))
    return None


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog='python -m koreader_d00901.feeds', description=__doc__)
    parser.add_argument('--feeds', type=Path, help='feed TOML (default: the bundled list)')
    parser.add_argument('--check', action='store_true', help='fetch and parse every feed marked check = true')
    parser.add_argument('--lua', action='store_true', help='print the generated feed_config.lua')
    args = parser.parse_args(argv)
    try:
        feeds = load_feeds(args.feeds)
    except ConfigError as exc:
        print(f'error: {exc}', file=sys.stderr)
        return 1
    if args.lua:
        print(render_lua(feeds), end='')
    if not args.check:
        if not args.lua:
            for feed in feeds:
                print(f'{"on " if feed.enabled else "off"} {feed.section:11} {feed.name}')
        return 0
    problems = []
    for feed in feeds:
        if not feed.check:
            print(f'skip {feed.name} (check = false)')
            continue
        if problem := check_feed(feed):
            problems.append(problem)
        else:
            print(f'ok   {feed.name}')
    if problems:
        print(f'{len(problems)} feed problem(s):', file=sys.stderr)
        for problem in problems:
            print(f'- {problem}', file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
